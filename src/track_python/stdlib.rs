//!
//! Both are embedded rather than derived. `GoResolver::is_stdlib`'s heuristic
//! — "the first path segment contains no dot" — is **inverted** for Python
//! (B-23): every third-party top-level name contains no dot either, so
//! applying it unchanged would classify `requests` and `numpy` as standard
//! library and hand them an `External` outcome nothing in the project
