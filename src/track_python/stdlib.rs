/// The package string an `External` outcome carries for the standard library.
///
/// Distribution granularity, not module granularity: `os.path` and `os` are
/// one shipped thing, and a node per submodule would multiply external nodes
/// without telling a reader anything the top-level name does not.
pub fn stdlib_package(top: &str) -> String {
    format!("py:std:{top}")
}

/// The package string an `External` outcome carries for the builtins scope.
pub const BUILTINS_PACKAGE: &str = "py:builtins";

/// Whether a top-level module name is in the standard library (B-23).
pub fn is_stdlib(top: &str) -> bool {
    STDLIB.binary_search(&top).is_ok()
}

/// Whether a bare name is bound by the builtins namespace (§4.2.2).
pub fn is_builtin(name: &str) -> bool {
    BUILTINS.binary_search(&name).is_ok()
}

/// Everything `object` declares — `dir(object)` on CPython 3.11, sorted.
///
/// Frozen for the same reason [`STDLIB`] is: it names something outside every
/// repository, so reading it from the running interpreter would make a scan
/// depend on which Python happened to be installed.
///
/// Deliberately exactly `dir(object)` and not a name more: the only use is
/// [`is_object_member`], and every name added here moves a `super()` call from
/// the rate's denominator into `External`. Under-listing keeps a reference in
/// the measurement; over-listing quietly removes it.
pub const OBJECT_MEMBERS: &[&str] = &[
    "__class__",
    "__delattr__",
    "__dir__",
    "__doc__",
    "__eq__",
    "__format__",
    "__ge__",
    "__getattribute__",
    "__getstate__",
    "__gt__",
    "__hash__",
    "__init__",
    "__init_subclass__",
    "__le__",
    "__lt__",
    "__ne__",
    "__new__",
    "__reduce__",
    "__reduce_ex__",
    "__repr__",
    "__setattr__",
    "__sizeof__",
    "__str__",
    "__subclasshook__",
];

/// Whether `object` itself declares this member (§3.3.2.1).
///
/// What a `super()` call in a class with no declared base can be answered
/// against: the implicit base is `object`, and only a member `object` really
/// has is a real target outside the repository.
pub fn is_object_member(name: &str) -> bool {
    OBJECT_MEMBERS.binary_search(&name).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn both_lists_are_sorted_because_both_are_binary_searched() {
        assert!(STDLIB.windows(2).all(|w| w[0] < w[1]), "STDLIB is unsorted");
        assert!(
            BUILTINS.windows(2).all(|w| w[0] < w[1]),
            "BUILTINS is unsorted"
        );
    }

    #[test]
    fn the_go_heuristic_is_not_reused() {
        // B-23: Go calls a path with no dot in its first segment stdlib. Every
        // one of these has no dot and none is standard library, which is the
        // whole reason this file exists.
        for third_party in ["requests", "numpy", "django", "scrapy", "sqlalchemy"] {
            assert!(!is_stdlib(third_party), "{third_party}");
        }
        for std in ["os", "json", "typing", "importlib", "__future__"] {
            assert!(is_stdlib(std), "{std}");
        }
    }

    #[test]
    fn builtins_cover_the_names_a_bare_call_actually_reaches() {
        for name in [
            "print",
            "len",
            "super",
            "isinstance",
            "ValueError",
            "object",
        ] {
            assert!(is_builtin(name), "{name}");
        }
        assert!(!is_builtin("helper"));
    }
}
